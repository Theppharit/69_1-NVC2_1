# ให้นักเรียนใช้เงื่อนไข while loop ในการเขียนโปรแกรมแสดงสูตรคูณ 1-12 ของตัวเลขที่ผู้ใช้ป้อนเข้ามา

try:
    # รับค่าและแปลงเป็นตัวเลข
    num = int(input("กรุณาป้อนแม่สูตรคูณ (ใส่เฉพาะตัวเลข): "))
    
    i = 1
    while i <= 12:
        print(f"{num} x {i} = {num * i}")
        i += 1

except ValueError:
    print("ข้อผิดพลาด: กรุณาป้อนเฉพาะตัวเลขจำนวนเต็มเท่านั้น (เช่น 5 หรือ 12)")
    