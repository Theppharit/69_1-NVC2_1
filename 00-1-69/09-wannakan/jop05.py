# 1. สร้าง List เก็บชื่อ-นามสกุลของเพื่อน 5 คน
friends = [
    "ธัญชนก มังจันทึก",
    "พิมพ์ลภัส ดีสวัสดิ์",
    "เกศสิรีย์ แสงกันยา",
    "นันทิกานต์ รวมกลาง",
    "ปิยฉัตร เคยพุดซา"
]

# ใช้ for loop แสดงผลลำดับที่และชื่อ-นามสกุล
for i in range(len(friends)):
    print(f"ลำดับที่ {i + 1} {friends[i]}")