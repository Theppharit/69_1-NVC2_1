try:
    # รับค่าและแปลงเป็นตัวเลข
    num = int(input("กรุณาป้อนแม่สูตรคูณ (ใส่เฉพาะตัวเลข) : "))
    
    i = 1
    while i <= 12:
        print(f"{num} x {i} = {num * i}")
        i += 1  # ขยับเข้ามาให้อยู่ในบล็อกของ while
        
except ValueError:
    print("ข้อผิดพลาด: กรุณาป้อนเฉพาะตัวเลขจำนวนเต็มเท่านั้น (เช่น 5 หรือ 12)")  # ขยับเข้ามาให้อยู่ในบล็อกของ except